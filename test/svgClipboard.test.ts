/**
 * @fileoverview クリップボードSVG文字列の受け入れ条件と、draw.io SVGの判定条件を検証する。
 */
import { describe, expect, it } from "vitest";
import { createDrawioPlaceholderSvg } from "../src/shared/drawioSvg";
import { findDrawioModelRange, normalizeSvgClipboardText } from "../src/shared/svgClipboard";

describe("normalizeSvgClipboardText", () => {
  it("accepts a normal SVG document", () => {
    const source = '  <svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0h1v1z"/></svg>  ';
    expect(normalizeSvgClipboardText(source)).toBe(source.trim());
  });

  it("accepts XML declaration, comments, and SVG doctype", () => {
    const source = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<!-- generated -->',
      '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">',
      '<svg xmlns="http://www.w3.org/2000/svg"></svg>',
    ].join("\n");
    expect(normalizeSvgClipboardText(source)).toBe(source);
  });

  it("accepts an empty self-closing SVG root", () => {
    expect(normalizeSvgClipboardText("<svg viewBox=\"0 0 1 1\"/>")).toBe(
      "<svg viewBox=\"0 0 1 1\"/>",
    );
  });

  it("rejects HTML that merely contains an SVG", () => {
    expect(normalizeSvgClipboardText("<div><svg></svg></div>")).toBeUndefined();
  });

  it("rejects arbitrary text around an SVG", () => {
    expect(normalizeSvgClipboardText("before <svg></svg>")).toBeUndefined();
    expect(normalizeSvgClipboardText("<svg></svg> after")).toBeUndefined();
  });

  it("rejects non-SVG clipboard text", () => {
    expect(normalizeSvgClipboardText("plain text")).toBeUndefined();
    expect(normalizeSvgClipboardText("<img src=\"x.png\">")).toBeUndefined();
  });
});

/**
 * draw.ioの編集モデルを持つSVGかを判定する。
 * @param svg - 判定するSVG文字列。
 * @returns モデルの範囲が見つかればtrue。
 */
const isDrawioSvg = (svg: string): boolean => findDrawioModelRange(svg) !== undefined;

/** 誤判定すると通常のSVGがdraw.ioエディターで開かれ、見逃すと再編集できなくなるため、両方向を確認する。 */
describe("findDrawioModelRange", () => {
  /** このリポジトリが生成する図は、貼り付け時もdraw.io SVGとして認識される必要がある。 */
  it("detects the SVG generated by this extension", () => {
    expect(isDrawioSvg(createDrawioPlaceholderSvg())).toBe(true);
  });

  /** draw.ioの書き出しにある属性順・引用符・エスケープの違いで判定結果を変えない。 */
  it.each([
    ["XML-escaped", '<svg content="&lt;mxfile host=&quot;a&quot;&gt;&lt;/mxfile&gt;"></svg>'],
    ["numeric decimal escape", '<svg content="&#60;mxfile host=&#34;a&#34;&#62;&#60;/mxfile&#62;"></svg>'],
    ["numeric hex escape", '<svg content="&#x3C;mxfile/>"></svg>'],
    ["literal < from outerHTML", '<svg content="<mxfile host=&quot;a&quot;></mxfile>"></svg>'],
    ["single quotes", "<svg content='&lt;mxfile&gt;&lt;/mxfile&gt;'></svg>"],
    ["other attributes first", '<svg xmlns="http://www.w3.org/2000/svg" width="1" content="&lt;mxfile&gt;"></svg>'],
    ["attribute after a value containing >", '<svg aria-label="a>b" content="&lt;mxfile&gt;"></svg>'],
    ["XML declaration and comment", '<?xml version="1.0"?>\n<!-- c -->\n<svg content="&lt;mxfile&gt;"></svg>'],
    ["doctype", '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "x.dtd">\n<svg content="&lt;mxfile&gt;"></svg>'],
    ["self-closing root", '<svg content="&lt;mxfile&gt;"/>'],
  ])("accepts %s", (_name, svg) => {
    expect(isDrawioSvg(svg)).toBe(true);
  });

  /** ルートのcontent属性がmxfileで始まる場合だけを対象にし、通常のSVGの拡張子を変えない。 */
  it.each([
    ["plain SVG", '<svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0"/></svg>'],
    ["other content value", '<svg content="hello"></svg>'],
    ["empty content", '<svg content=""></svg>'],
    ["similar element name", '<svg content="&lt;mxfileX&gt;"></svg>'],
    ["mxfile not at the start", '<svg content="x &lt;mxfile&gt;"></svg>'],
    ["similar attribute name", '<svg data-content="&lt;mxfile&gt;"></svg>'],
    ["content text inside another attribute", `<svg aria-label='content="&lt;mxfile&gt;"'></svg>`],
    ["nested svg only", '<svg><svg content="&lt;mxfile&gt;"></svg></svg>'],
    ["body text only", "<svg><text>&lt;mxfile&gt;</text></svg>"],
    ["commented out", '<!-- <svg content="&lt;mxfile&gt;"> --><svg></svg>'],
    ["not an SVG", '<svgx content="&lt;mxfile&gt;"></svgx>'],
    ["unterminated root tag", '<svg content="&lt;mxfile&gt;'],
    ["empty", ""],
  ])("rejects %s", (_name, svg) => {
    expect(isDrawioSvg(svg)).toBe(false);
  });

  /** 返す範囲は引用符を除いたモデルの値そのもので、復元処理の位置照合に使える。 */
  it("returns the exact range of the model value", () => {
    const model = "&lt;mxfile&gt;&lt;/mxfile&gt;";
    const svg = `<?xml version="1.0"?>\n<svg width="1" content="${model}"></svg>`;
    const range = findDrawioModelRange(svg);
    expect(range && svg.slice(range.start, range.end)).toBe(model);
  });

  /** draw.ioの実際の書き出しにある先頭部分は、許可リストの範囲に収まる必要がある。 */
  it("accepts the header written by draw.io", () => {
    const svg = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<!-- Do not edit this file with editors other than draw.io -->',
      '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">',
      '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" version="1.1"',
      '  width="161px" height="49px" viewBox="-0.5 -0.5 161 49"',
      '  content="&lt;mxfile&gt;&lt;/mxfile&gt;"></svg>',
    ].join("\r\n");
    expect(isDrawioSvg(svg)).toBe(true);
  });

  /** XML宣言は単引用符、standalone、大小文字の異なるUTF-8でも正規の形として受け入れる。 */
  it("accepts every valid form of the XML declaration", () => {
    expect(isDrawioSvg(`<?xml version='1.0' encoding='utf-8' standalone='no' ?><svg content="&lt;mxfile&gt;"></svg>`)).toBe(true);
    expect(isDrawioSvg('<?xml version="1.0"?><svg content="&lt;mxfile&gt;"></svg>')).toBe(true);
  });

  /**
   * XMLとHTMLで解釈が分かれる文書では、content属性に見える範囲がブラウザーでは実行可能なマークアップになる。
   * 判定範囲はサニタイズの対象外になるため、これらをdraw.io SVGと認めるとサニタイズの迂回になる。
   */
  it.each([
    ["entity value with a fake root", `<!DOCTYPE svg [<!ENTITY e "><svg content='<mxfile ">]><svg xmlns="x"><script>1</script><g a='x'/></svg>`],
    ["internal subset", '<!DOCTYPE svg [<!ENTITY e "x">]><svg content="&lt;mxfile&gt;"></svg>'],
    ["empty attribute name", '<svg =a="x content="<mxfile><script>1</script>"></svg>'],
    ["slash before an equals sign", '<svg a/=b="x content="<mxfile><img src=x onerror=1>"></svg>'],
    ["attribute without a space", '<svg/content="&lt;mxfile&gt;"></svg>'],
    ["no space between attributes", '<svg a="1"content="&lt;mxfile&gt;"></svg>'],
    ["unquoted value", '<svg width=1 content="&lt;mxfile&gt;"></svg>'],
    ["unquoted content", "<svg content=&lt;mxfile&gt;></svg>"],
    ["attribute without a value", '<svg hidden content="&lt;mxfile&gt;"></svg>'],
    ["comment closed early in HTML", `<!--><a title=" --><svg content="<mxfile><script>1</script>"></svg>`],
    ["comment with --!>", `<!-- --!><a title=" --><svg content="<mxfile><script>1</script>"></svg>`],
    ["XML declaration with >", `<?xml a="><b title='" ?><svg content="<mxfile><script>1</script>"></svg>`],
    ["doctype literal with >", `<!DOCTYPE svg SYSTEM "><a title='"><svg content="<mxfile>"></svg>`],
    ["non-UTF-8 encoding", '<?xml version="1.0" encoding="ISO-2022-JP"?><svg content="&lt;mxfile&gt;"></svg>'],
    ["encoding hidden in the version value", `<?xml version="encoding='ISO-2022-JP'"?><svg content="&lt;mxfile&gt;"></svg>`],
    ["encoding appended to the version value", `<?xml version="1.0 encoding='ISO-2022-JP'"?><svg content="&lt;mxfile&gt;"></svg>`],
    ["encoding hidden in the standalone value", `<?xml version="1.0" standalone="encoding='ISO-2022-JP'"?><svg content="&lt;mxfile&gt;"></svg>`],
    ["encoding in a standalone-only declaration", `<?xml standalone="encoding='ISO-2022-JP'"?><svg content="&lt;mxfile&gt;"></svg>`],
    ["unknown XML declaration attribute", '<?xml version="1.0" a="1"?><svg content="&lt;mxfile&gt;"></svg>'],
    ["NBSP separator", '<svg\u00a0content="&lt;mxfile&gt;"></svg>'],
    ["uppercase root", '<SVG content="&lt;mxfile&gt;"></SVG>'],
  ])("does not trust %s", (_name, svg) => {
    expect(isDrawioSvg(svg)).toBe(false);
  });

  /**
   * 細工された開始タグでもExtension Hostを止めず、例外も出さない。
   * 同期処理のため、入力を大きくしすぎると二次時間への退行で失敗せずテストが止まる。
   * この長さなら退行時は数十秒かかり、上限の超過として検出できる。
   */
  it.each([
    ["one long token", `<svg ${"a".repeat(300_000)}></svg>`, false],
    ["many attributes", `<svg ${'a="1" '.repeat(50_000)}></svg>`, false],
    ["long quote-leading token", `<svg "${"x".repeat(300_000)}"></svg>`, false],
    ["unterminated quote", `<svg a="${"x".repeat(300_000)}`, false],
    ["XML declaration with many attributes", `<?xml ${'a="1" '.repeat(3_500_000)}?><svg content="&lt;mxfile&gt;"></svg>`, false],
    ["long unterminated comment", `<!--${"-".repeat(300_000)}`, false],
    ["many prolog comments", `${"<!-- c -->".repeat(30_000)}<svg content="&lt;mxfile&gt;"></svg>`, true],
    ["huge model", `<svg content="&lt;mxfile&gt;${"x".repeat(32 * 1024 * 1024)}"></svg>`, true],
  ])("scans %s in linear time", (_name, svg, expected) => {
    const startedAt = performance.now();
    expect(isDrawioSvg(svg)).toBe(expected);
    expect(performance.now() - startedAt).toBeLessThan(3000);
  });
});
