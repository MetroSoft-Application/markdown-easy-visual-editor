/**
 * 挿入リボンの「空行」ボタンが挿入する文字列。プレビューで1行分の空白を作る`<br>`の後ろに空行を置く。
 * 末尾の空行は、`<br>`から始まるCommonMarkのHTMLブロックを閉じ、次の行がHTMLブロックへ取り込まれて
 * Markdownとして描画されなくなることを防ぐ。改行は`\n`で表し、挿入時に文書の改行コードへ変換される。
 * 段落の行末で挿入すると`<br>`はその段落内の末尾改行になり、ブラウザーでは空白行として表示されない場合がある。
 */
export const BLANK_LINE_SNIPPET = "<br>\n\n";
